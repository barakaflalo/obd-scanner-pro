#!/usr/bin/env python3
# Builds src/maker/<key>.js from OBDb signal sets (https://github.com/OBDb, CC BY-SA 4.0).
# Usage: python3 tools/maker-pack.py            (builds every pack listed in PACKS)
import json, os, collections
PACKS = {
  "toyota": ["Lexus", "Toyota", "Daihatsu"], "vag": ["Volkswagen", "Audi", "Skoda", "SEAT", "Cupra", "Porsche"], "hk": ["Hyundai", "Kia", "Genesis"],
  "ford": ["Ford", "Lincoln"], "mazda": ["Mazda"], "gm": ["Chevrolet", "GMC", "Buick", "Cadillac"], "nissan": ["Nissan", "Infiniti"], "renault": ["Renault", "Dacia"],
  "stellantis": ["Peugeot", "Citroen", "Fiat", "Jeep", "Dodge", "Chrysler", "Ram", "Alfa-Romeo"], "honda": ["Honda", "Acura"], "mitsubishi": ["Mitsubishi"],
  "subaru": ["Subaru"], "volvo": ["Volvo", "Polestar"], "jlr": ["Jaguar", "Land-Rover"], "mg": ["MG"], "byd": ["BYD"],
}
here = os.path.dirname(os.path.abspath(__file__))
def build(key, files):
    raw = []
    for f in files: raw += json.load(open(os.path.join(here, "obdb", f + ".json"), encoding="utf-8"))["commands"]
    # reply address of each 11-bit ECU, learned from the commands that state it
    rx = collections.defaultdict(collections.Counter)
    for c in raw:
        if c.get("rax") and len(c["hdr"]) == 3 and len(c["rax"]) == 3: rx[c["hdr"]][c["rax"]] += 1
    cmds = {}
    for c in raw:
        if c.get("eax") or c.get("proto") or c.get("init") or c.get("din") or c.get("dout"): continue
        h = c["hdr"]; rax = c.get("rax")
        if len(h) == 3 and h != "7DF":
            if rax and len(rax) != 3: continue
            rax = rax or (rx[h].most_common(1)[0][0] if rx[h] else "%03X" % (int(h, 16) + 8))
        elif len(h) == 4 and h.startswith("DA") and (not rax or rax == h[2:]): rax = h[2:]   # 29-bit: 18 DA xx F1 → 18 DA F1 xx
        else: continue
        svc, pid = list(c["cmd"].items())[0]
        if svc not in ("21", "22"): continue
        dst = cmds.setdefault((h, rax, svc, pid), {})
        for s in c["signals"]:
            m = s["fmt"]
            if "blsb" in m or "len" not in m or m["len"] > 32: continue
            fk = (m.get("bix", 0), m["len"], m.get("mul", 1), m.get("div", 1), m.get("add", 0), bool(m.get("sign")))
            if fk in dst: continue
            o = {"n": s["name"], "p": (s.get("path") or "Other").split(".")[0], "b": m.get("bix", 0), "l": m["len"]}
            for a, b in (("mul", "m"), ("div", "d"), ("add", "a"), ("min", "lo"), ("max", "hi"), ("nullmin", "nl"), ("nullmax", "nh")):
                if a in m and not (a in ("mul", "div") and m[a] == 1) and not (a == "add" and m[a] == 0): o[b] = m[a]
            if m.get("sign"): o["s"] = 1
            if m.get("unit"): o["u"] = m["unit"]
            if m.get("map"): o["map"] = {str(k2): (v.get("description") or v.get("value")) for k2, v in m["map"].items()}
            dst[fk] = o
    out = [{"h": k[0], "r": k[1], "s": k[2], "p": k[3], "g": sorted(v.values(), key=lambda o: o["b"])} for k, v in sorted(cmds.items()) if v]
    js = "// Generated by tools/maker-pack.py — data from OBDb (https://github.com/OBDb), licensed CC BY-SA 4.0.\n// This file stays under CC BY-SA 4.0.\nexport default " + json.dumps({"src": "OBDb", "url": "https://github.com/OBDb", "lic": "CC BY-SA 4.0", "cmds": out}, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open(os.path.join(here, "..", "src", "maker", key + ".js"), "w", encoding="utf-8").write(js)
    n11 = sum(1 for c in out if len(c["h"]) == 3)
    print(f"{key:11} {len(out):5} cmds ({n11} 11-bit, {len(out)-n11} 29-bit) {sum(len(c['g']) for c in out):5} signals {len(set(c['h'] for c in out)):3} ecus {len(js)//1024:4} KB  paths:", sorted({g['p'] for c in out for g in c['g']} - set("Battery Brakes Climate Control DTCs Details Doors Drivetrain ECU Electrical Engine Fluids Fuel Lights Movement Orientation Other Seatbelts Stats Tires Transmission Trips".split()) - {"Cruise control"}), sorted({g.get('u','') for c in out for g in c['g']} - set("ampereHours amps bars celsius degrees fahrenheit gallons gramsPerSecond gravity hertz hours kilometers kilometersPerHour kilopascal kilowatts liters megaohms meters metersPerSecondSquared milliamps millimeters milliohms milliseconds minutes newtonMeters noyes offon ohms onoff percent psi rpm scalar seconds unknown volts watts yesno".split()) - {""}))
for k, f in PACKS.items(): build(k, f)
